#!/usr/bin/env python3
"""Generate the lookup tables of the rubik solver.

    python3 src/rubik/gen_tables.py

writes src/rubik/rubik_tables.h for the C version and src/rubik/rubik_data.S
for the assembly version. Both carry the same four tables:

  pn[f][p]  the permutation rank after a quarter turn of face f (R, B, D)
  on[f][o]  the orientation rank after a quarter turn of face f
  near[]    every state within 5 moves of solved, as (key << 3) | distance,
            sorted, where key = (p << 10) | o
  far[]     every state at distance 11 (the diameter), as a sorted key

p is the Lehmer rank of the seven cubie places (0..5039) and o the base-3
number of the first six twists (0..728); the solved cube is p = o = 0. The
tables are partial: the full distance table of all 3,674,160 states is built
here, on the host, only to select near[] and far[]; it is not emitted.
"""

import os
import sys

CUBIES = 7
PERMS = 5040
TWISTS = 729
NEAR_SHIFT = 12  # bucket of a key in the assembly's index of near[]

SOURCE = (
    (1, 4, 2, 0, 3, 5, 6),
    (0, 1, 2, 4, 5, 6, 3),
    (0, 2, 5, 3, 1, 4, 6),
)
TWIST = (
    (1, 2, 0, 2, 1, 0, 0),
    (0, 0, 0, 1, 2, 1, 2),
    (0, 0, 0, 0, 0, 0, 0),
)


def rank_perm(p):
    r = 0
    for i in range(CUBIES):
        smaller = sum(1 for j in range(i + 1, CUBIES) if p[j] < p[i])
        r = r * (CUBIES - i) + smaller
    return r


def unrank_perm(r):
    avail = list(range(CUBIES))
    p = []
    for i in range(CUBIES):
        f = 1
        for k in range(1, CUBIES - i):
            f *= k
        q, r = divmod(r, f)
        p.append(avail.pop(q))
    return p


def rank_orient(o):
    r = 0
    for i in range(CUBIES - 1):
        r = r * 3 + o[i]
    return r


def unrank_orient(r):
    o = [0] * CUBIES
    for i in range(CUBIES - 2, -1, -1):
        r, o[i] = divmod(r, 3)
    o[CUBIES - 1] = (-sum(o[:CUBIES - 1])) % 3
    return o


def build():
    pn = [[0] * PERMS for _ in range(3)]
    on = [[0] * TWISTS for _ in range(3)]
    for r in range(PERMS):
        p = unrank_perm(r)
        assert rank_perm(p) == r
        for f in range(3):
            pn[f][r] = rank_perm([p[SOURCE[f][i]] for i in range(CUBIES)])
    for r in range(TWISTS):
        o = unrank_orient(r)
        assert rank_orient(o) == r
        for f in range(3):
            on[f][r] = rank_orient(
                [(o[SOURCE[f][i]] + TWIST[f][i]) % 3 for i in range(CUBIES)])

    # Breadth-first search over all states, from solved, by quarter turns
    # applied one to three times (the nine moves).
    dist = bytearray(b"\xff") * (PERMS * TWISTS)
    dist[0] = 0
    frontier = [0]
    depth = 0
    counts = [1]
    while frontier:
        nxt = []
        for s in frontier:
            p, o = divmod(s, TWISTS)
            for f in range(3):
                pf, of = pn[f], on[f]
                q, t = p, o
                for _ in range(3):
                    q, t = pf[q], of[t]
                    k = q * TWISTS + t
                    if dist[k] == 255:
                        dist[k] = depth + 1
                        nxt.append(k)
        if nxt:
            counts.append(len(nxt))
        frontier = nxt
        depth += 1
    assert sum(counts) == PERMS * TWISTS, counts

    near, far = [], []
    for k in range(PERMS * TWISTS):
        d = dist[k]
        p, o = divmod(k, TWISTS)
        key = (p << 10) | o
        if d <= 5:
            near.append((key << 3) | d)
        elif d == 11:
            far.append(key)
    near.sort()
    far.sort()
    return pn, on, near, far, counts


def c_array(decl, values, per_line=12):
    lines = [decl + " = {"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def c_array2d(decl, rows, per_line=12):
    lines = [decl + " = {"]
    for row in rows:
        lines.append("    {")
        for i in range(0, len(row), per_line):
            lines.append("        " + ", ".join(str(v) for v in row[i:i + per_line]) + ",")
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines)


def s_array(label, directive, values, per_line=12):
    lines = ["    .globl  " + label, "    .type   " + label + ", @object",
             label + ":"]
    for i in range(0, len(values), per_line):
        lines.append("    " + directive + " " +
                     ", ".join(str(v) for v in values[i:i + per_line]))
    lines.append("    .size   " + label + ", .-" + label)
    return "\n".join(lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    pn, on, near, far, counts = build()
    note = ("Generated by src/rubik/gen_tables.py. Do not edit.\n"
            " * States per distance: " + " ".join(map(str, counts)) + ".")

    h = ["/* " + note + " */", "#pragma once", "", "#include <stdint.h>", "",
         "enum { RUBIK_NEAR = %d, RUBIK_FAR = %d };" % (len(near), len(far)),
         ""]
    h.append(c_array2d("static const uint16_t rubik_pn[3][5040]", pn))
    h.append("")
    h.append(c_array2d("static const uint16_t rubik_on[3][729]", on))
    h.append("")
    h.append(c_array("static const uint32_t rubik_near[RUBIK_NEAR]", near, 8))
    h.append("")
    h.append(c_array("static const uint32_t rubik_far[RUBIK_FAR]", far, 8))
    with open(os.path.join(here, "rubik_tables.h"), "w") as f:
        f.write("\n".join(h) + "\n")

    # The assembly lays the tables out for its addressing:
    #   pn and on: four halfwords per rank, one per face and one unused, so
    #     the entry of face f is at (rank << 3) + (f << 1);
    #   near and far: a sentinel 0xFFFFFFFF after the last entry, so a search
    #     that runs off the end reads a key larger than any;
    #   nidx[b]: the index of the first near entry whose key >> NEAR_SHIFT is
    #     at least b, so the search of a key only scans its own bucket.
    pn4 = [v for r in range(PERMS) for v in (pn[0][r], pn[1][r], pn[2][r], 0)]
    on4 = [v for r in range(TWISTS)
           for v in (on[0][r], on[1][r], on[2][r], 0)]
    buckets = ((PERMS - 1) << 10 | (TWISTS - 1)) >> NEAR_SHIFT
    nidx = []
    i = 0
    for b in range(buckets + 2):
        while i < len(near) and (near[i] >> 3) >> NEAR_SHIFT < b:
            i += 1
        nidx.append(i)
    s = ["# " + note.replace("\n * ", "\n# "), "",
         "    .section .rodata", "    .align  2", ""]
    s.append(s_array("rubik_asm_pn", ".half", pn4))
    s.append("")
    s.append(s_array("rubik_asm_on", ".half", on4))
    s.append("")
    s.append(s_array("rubik_asm_nidx", ".half", nidx))
    s.append("")
    s.append("    .align  2")
    s.append(s_array("rubik_asm_near", ".word", near + [0xFFFFFFFF], 8))
    s.append("")
    s.append(s_array("rubik_asm_far", ".word", far + [0xFFFFFFFF], 8))
    with open(os.path.join(here, "rubik_data.S"), "w") as f:
        f.write("\n".join(s) + "\n")

    print("distances:", counts, file=sys.stderr)
    print("near:", len(near), "far:", len(far), file=sys.stderr)


if __name__ == "__main__":
    main()
